#!/usr/bin/env python3
"""Generate immutable fixture defaults and theme constants. No dependency download.
The JSON files are the only editable fixture source; generated/ is derived.
"""
from pathlib import Path
import argparse, json
ROOT=Path(__file__).resolve().parents[1]
def q(s): return json.dumps(s, ensure_ascii=True)
def generate():
 s=json.loads((ROOT/'fixtures/session.json').read_text(encoding='utf-8'))
 lines=['// Generated by tools/generate.py. Edit fixtures/session.json, not this file.', '#include "LabModel.h"', '#include <utility>', 'namespace ayra::lab {', 'Session makeFixture()', '{', '    Session s;']
 for key in ['songId','active','selectedClip']: lines.append(f'    s.{key} = {q(s[key])};')
 lines += [f'    s.mode = Mode::{"grouped" if s["mode"]=="grouped" else "free"};', f'    s.dark = {str(s["dark"]).lower()};',f'    s.groupCollapsed = {str(s["groupCollapsed"]).lower()};',f'    s.headerWidth = {s["headerWidth"]};',f'    s.zoom = {s["zoom"]};']
 for key in ['manualOrder','selected']:lines.append(f'    s.{key} = {{{", ".join(map(q,s[key]))}}};')
 for t in s['tracks']:
  lines+=['    {','        Track t;']
  for key in ['id','name','group','groupName','route','monitor']:lines.append(f'        t.{key} = {q(t[key])};')
  lines+=[f'        t.role = Role::{t["role"]};', f'        t.colour = 0xff{t["colour"][1:]}u;']
  for key in ['height','audioChannels','midiPins','oscPins','dmxPins','automations','gain','pan']:lines.append(f'        t.{key} = {t[key]};')
  for key in ['expanded','pinned','mute','solo','enabled','bypass','buffer','oversample']:lines.append(f'        t.{key} = {str(t[key]).lower()};')
  lines.append(f'        t.order = {{{", ".join(map(str,t["order"]))}}};')
  for c in t['clips']:
   lines.append('        t.clips.push_back({'+', '.join([q(c['id']),q(c['name'])]+[str(c[k]) for k in ['start','length','channels','seed','fadeIn','fadeOut']])+'});')
  lines+=['        s.tracks.push_back(std::move(t));','    }']
 lines+=['    return s;','}','}']
 outputs={'generated/FixtureData.cpp':'\n'.join(lines)+'\n'}
 theme=json.loads((ROOT/'fixtures/theme.json').read_text(encoding='utf-8'))
 lines=['// Generated by tools/generate.py. Frozen lab snapshot, not production tokens.','#pragma once','#include <cstdint>','namespace ayra::lab::themeSnapshot {']
 for key in ['dark','light','semantic']:
  lines.append(f'namespace {key} {{')
  for name,value in theme[key].items():lines.append(f'inline constexpr std::uint32_t {name} = 0xff{value[1:]}u;')
  lines.append('}')
 lines.append('}')
 outputs['generated/ThemeData.h']='\n'.join(lines)+'\n'
 css=''
 for m in ['dark','light']:
  sel=':root' if m=='dark' else 'body.light'
  css+=sel+'{'+''.join(f'--{k}:{v};' for k,v in theme[m].items())+'}\n'
 css+=':root{'+''.join(f'--{k}:{v};' for k,v in theme['semantic'].items())+'}\n'
 outputs['generated/theme.css']=css
 return outputs
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 bad=[]
 for name,text in generate().items():
  path=ROOT/name
  if args.check:
   if not path.exists() or path.read_text(encoding='utf-8')!=text:bad.append(name)
  else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text, encoding='utf-8')
 if bad:raise SystemExit('Generated files differ: '+', '.join(bad))
 print('Generated sources: OK' if args.check else 'Generated sources written')
