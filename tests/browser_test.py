#!/usr/bin/env python3
"""Run actual DOM interactions. Requires Playwright and a Chromium executable.
No audio, native JUCE rendering, or production routing is exercised here.
"""
import argparse,json,shutil
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--chromium',default=shutil.which('chromium'));args=parser.parse_args()
results=[]
def check(ok,name):
 results.append({'test':name,'passed':bool(ok)})
 if not ok:raise AssertionError(name)
with sync_playwright() as p:
 kwargs={'headless':True,'args':['--no-sandbox']}
 if args.chromium:kwargs['executable_path']=args.chromium
 browser=p.chromium.launch(**kwargs)
 page=browser.new_page(viewport={'width':1620,'height':1200},accept_downloads=True)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 html=(ROOT/'web/ayra-header-lab.html').read_text(encoding='utf-8')
 def reset():page.goto("about:blank");page.set_content(html);page.wait_for_timeout(100)
 def state():return page.evaluate('lab.state')
 def tr(id):return next(t for t in state()['tracks'] if t['id']==id)
 reset()
 check(page.locator('[data-header]').count()==4,'Four role headers')
 check(page.locator('[data-header="main"] [data-action="solo"]').count()==0,'No invented Solo on Song Main')
 check(page.locator('.global').count()==6,'Six non-reorderable global lanes')
 check(page.locator('#arranger [data-clip="voice-take"] .clip-channel').count()==4,'Stereo drawn in four positions')
 check(page.locator('#arranger [data-clip="voice-take"] .empty-channel').count()==2,'Two empty positions preserved')
 page.locator('[data-header="backing"]').click(position={'x':180,'y':15})
 check(state()['selected']==['backing'],'Header selection distinct from clip selection')
 check(state()['selectedClip']=='voice-take','Header click does not select clips')
 page.locator('[data-header="voice"]').click(position={'x':180,'y':15},modifiers=['Control'])
 check(set(state()['selected'])=={'voice','backing'},'Ctrl multiselection')
 page.locator('[data-header="mix"]').click(position={'x':180,'y':15},modifiers=['Shift'])
 check(state()['selected']==['voice','mix'],'Shift range uses visible order')
 page.locator('[data-header="voice"] [data-action="mute"]').click()
 check(tr('voice')['mute'],'Header mute writes shared fixture state')
 check(page.locator('[data-select="voice"] [data-action="mute"]').get_attribute('aria-pressed')=='true','Mixer follows header mute')
 page.locator('[data-header="voice"] [data-action="solo"]').click()
 check(tr('voice')['solo'] and not tr('voice')['mute'],'Mute and solo exclusion')
 page.locator('[data-header="voice"] [data-action="mute"]').click(button='right')
 check(page.locator('#dialog').is_visible() and tr('voice')['solo'],'Right-click does not toggle mute')
 page.locator('#dialog-close').click()
 page.locator('[data-header="main"] [data-action="mute"]').click()
 check(not tr('voice')['mute'],'Program mute does not mutate child mute')
 check('Cue attive' in page.locator('#inspector').inner_text(),'Program versus Cue distinction')
 reset()
 before=tr('voice')['height'];handle=page.locator('[data-resize="voice"]');box=handle.bounding_box();page.mouse.move(box['x']+150,box['y']+3);page.mouse.down();page.mouse.move(box['x']+150,box['y']+63,steps=6);page.mouse.up()
 check(tr('voice')['height']==before+60,'Resize commits new height')
 page.locator('#undo').click();check(tr('voice')['height']==before,'Resize one-step Undo')
 box=page.locator('[data-resize="voice"]').bounding_box();page.mouse.move(box['x']+150,box['y']+3);page.mouse.down();page.mouse.move(box['x']+150,box['y']+43,steps=4);page.keyboard.press('Escape');page.mouse.up()
 check(tr('voice')['height']==before,'Escape cancels resize without commit')
 page.locator('[data-header="voice"] [data-action="expanded"]').click()
 check(page.locator('[data-row="voice"] .other-lane').count()==5,'Expansion exposes 3 MIDI pins, OSC, automation context')
 check(len(tr('voice')['order'])==4,'Expand does not change mapping')
 reset();page.locator('#free').click()
 source=page.locator('[data-drag="voice"]');target=page.locator('[data-row="backing"]')
 source.drag_to(target,target_position={'x':130,'y':12})
 check(state()['manualOrder']==['voice','backing','mix','main'],'Real DOM drag-and-drop through grip')
 reset();domain=state()['tracks'];page.locator('#free').click()
 check(page.locator('[data-drag="voice"]').is_enabled(),'Free mode enables grip')
 check(not page.locator('[data-drag="main"]').is_enabled(),'Pinned main protected')
 check(page.evaluate("lab.move(['voice','mix'],'backing',false)"),'Identity-based reorder')
 check(state()['manualOrder']==['voice','mix','backing','main'],'Stable block reorder')
 check(state()['tracks']==domain,'Reorder leaves clips routing and colour untouched')
 page.locator('#grouped').click();page.locator('#free').click()
 check(state()['manualOrder']==['voice','mix','backing','main'],'Mode toggles preserve manual order')
 check(page.locator('[data-select]').evaluate_all('(els)=>els.map(e=>e.dataset.select)')==page.evaluate('lab.ordered()'),'Mixer and timeline same order')
 page.locator('[data-header="main"] [data-action="pinned"]').click()
 check(page.evaluate("lab.move(['main'],'voice',false)"),'Unpinned main movable')
 reset();page.locator('#arranger [data-clip="voice-take"]').dblclick(position={'x':100,'y':70})
 check(page.locator('#channels-button').is_visible(),'Double click opens clip editor with mapping entry')
 page.locator('#channels-button').click()
 check(page.locator('.mapping-row').count()==4,'Mapping is one list of N positions')
 check(page.locator('.mapping-row').nth(1).inner_text().find('Vuoto')>=0,'Mapping names empty positions')
 old=tr('voice')['order'];page.locator('[data-map-move="3"][data-step="-1"]').click()
 check(tr('voice')['order']==old,'Mapping draft not yet committed')
 page.locator('#map-apply').click()
 check(tr('voice')['order']==[0,2,1,3],'Mapping applied track-wide')
 check(tr('voice')['clips']==domain[1]['clips'],'Mapping does not modify source file data')
 page.locator('#undo').click();check(tr('voice')['order']==old,'Mapping one-step Undo')
 reset();page.locator('[data-header="voice"] [data-action="graph"]').click();check(page.locator('.route-node').count()==4,'Graph opens explicit fixture chain');page.locator('#dialog-close').click()
 page.locator('[data-header="voice"] [data-action="routing"]').click();check('sola lettura' in page.locator('#dialog-body').inner_text(),'Routing labelled read-only fixture');page.locator('#dialog-close').click()
 page.locator('[data-header="voice"] [data-action="automations"]').click();page.locator('#automation-add').click();check(tr('voice')['automations']==4,'Automation inventory fixture edit');page.locator('#dialog-close').click()
 reset();page.locator('#theme').click();check(page.locator('body').evaluate('(e)=>e.classList.contains("light")'),'Light theme')
 page.screenshot(path=str(ROOT/'verification/html-light.png'))
 page.locator('#theme').click();page.screenshot(path=str(ROOT/'verification/html-dark.png'))
 page.locator('#gallery-toggle').click()
 check(page.locator('body').evaluate('(e)=>e.classList.contains("gallery")'),'Four-role gallery toggle')
 page.screenshot(path=str(ROOT/'verification/header-gallery.png'))
 boxes=page.locator('[data-header]').evaluate_all('(els)=>els.map(e=>{const r=e.getBoundingClientRect();return {x:r.x,y:r.y,right:r.right,bottom:r.bottom}})')
 x=min(b['x'] for b in boxes)-10;y=min(b['y'] for b in boxes)-10
 right=max(b['right'] for b in boxes)+10;bottom=max(b['bottom'] for b in boxes)+10
 page.screenshot(path=str(ROOT/'verification/four-headers.png'),clip={'x':x,'y':y,'width':right-x,'height':bottom-y})
 page.locator('#gallery-toggle').click()
 check(page.evaluate("(()=>{let s=lab.state;s.manualOrder=['voice'];try{lab.validate(s);return false}catch(e){return true}})()"),'Reject malformed order')
 check(page.evaluate("(()=>{let s=lab.state;s.tracks[0].order=[0,0,2,3];try{lab.validate(s);return false}catch(e){return true}})()"),'Reject malformed channel mapping')
 check(page.evaluate("(()=>{let s=lab.state;s.schema='aym';try{lab.validate(s);return false}catch(e){return true}})()"),'Reject non-Lab schema')
 # Exported HTML must run from its own embedded state.
 page.locator('#free').click();page.locator('#save').click()
 with page.expect_download() as dl:page.locator('#export-html').click()
 file=ROOT/'verification/export-roundtrip.html';dl.value.save_as(file)
 page.goto('about:blank');page.set_content(file.read_text(encoding='utf-8'));check(state()['mode']=='free','HTML export reloads edited state');file.unlink()
 # 125%/150%/200% screenshots are browser device scale, not JUCE DPI certification.
 page.set_viewport_size({'width':1100,'height':800});check(page.locator('[data-header]').count()==4,'Narrow viewport still presents all entities')
 check(not errors,'No browser runtime exceptions')
 browser.close()
(ROOT/'verification/browser-results.json').write_text(json.dumps({'checks':len(results),'results':results},indent=2), encoding='utf-8')
print(f'PASS: {len(results)} browser checks')
